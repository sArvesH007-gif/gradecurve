-- Oracle Database Free 23ai/26ai compatible base tables for GradeCurve.
-- Run once in a dedicated, empty Oracle application schema.

CREATE TABLE users (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  username VARCHAR2(120 CHAR) NOT NULL,
  full_name VARCHAR2(160 CHAR) NOT NULL,
  password_hash VARCHAR2(200 CHAR) NOT NULL,
  user_role VARCHAR2(12 CHAR) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT users_pk PRIMARY KEY (user_id)
);

CREATE TABLE class_slots (
  slot_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR2(40 CHAR) NOT NULL,
  teacher_id NUMBER NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT class_slots_pk PRIMARY KEY (slot_id)
);

CREATE TABLE teacher_profiles (
  teacher_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id NUMBER NOT NULL,
  CONSTRAINT teacher_profiles_pk PRIMARY KEY (teacher_id)
);

CREATE TABLE student_profiles (
  student_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id NUMBER NOT NULL,
  registration_no VARCHAR2(24 CHAR) NOT NULL,
  program VARCHAR2(120 CHAR) DEFAULT 'B.Tech Computer Science' NOT NULL,
  semester NUMBER(2) DEFAULT 5 NOT NULL,
  active_slot_id NUMBER NOT NULL,
  CONSTRAINT student_profiles_pk PRIMARY KEY (student_id)
);

CREATE TABLE courses (
  course_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  code VARCHAR2(20 CHAR) NOT NULL,
  name VARCHAR2(160 CHAR) NOT NULL,
  semester NUMBER(2) DEFAULT 5 NOT NULL,
  teacher_id NUMBER NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT courses_pk PRIMARY KEY (course_id)
);

CREATE TABLE course_slots (
  course_slot_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  course_id NUMBER NOT NULL,
  slot_id NUMBER NOT NULL,
  CONSTRAINT course_slots_pk PRIMARY KEY (course_slot_id)
);

CREATE TABLE enrollments (
  enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  course_id NUMBER NOT NULL,
  slot_id NUMBER NOT NULL,
  enrolled_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT enrollments_pk PRIMARY KEY (enrollment_id)
);

CREATE TABLE assessments (
  assessment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  course_id NUMBER NOT NULL,
  name VARCHAR2(24 CHAR) NOT NULL,
  max_score NUMBER(7,2) NOT NULL,
  weight NUMBER(5,4) NOT NULL,
  due_date DATE,
  CONSTRAINT assessments_pk PRIMARY KEY (assessment_id)
);

CREATE TABLE marks (
  mark_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  assessment_id NUMBER NOT NULL,
  score NUMBER(7,2) NOT NULL,
  mark_source VARCHAR2(24 CHAR) DEFAULT 'FACULTY' NOT NULL,
  entered_by_user_id NUMBER,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT marks_pk PRIMARY KEY (mark_id)
);

CREATE TABLE mark_submissions (
  submission_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  assessment_id NUMBER NOT NULL,
  score NUMBER(7,2) NOT NULL,
  peer_scores_json CLOB DEFAULT '[]' NOT NULL,
  submission_status VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
  is_outlier NUMBER(1) DEFAULT 0 NOT NULL,
  reason VARCHAR2(500 CHAR) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT mark_submissions_pk PRIMARY KEY (submission_id)
);

CREATE TABLE mark_verifications (
  verification_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  submission_id NUMBER NOT NULL,
  reviewer_id NUMBER NOT NULL,
  decision VARCHAR2(12 CHAR) NOT NULL,
  official_score NUMBER(7,2),
  note VARCHAR2(500 CHAR),
  decided_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT mark_verifications_pk PRIMARY KEY (verification_id)
);

CREATE TABLE attendance (
  attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  course_id NUMBER NOT NULL,
  attendance_date DATE NOT NULL,
  present NUMBER(1) NOT NULL,
  CONSTRAINT attendance_pk PRIMARY KEY (attendance_id)
);

CREATE TABLE study_matches (
  study_match_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  requester_id NUMBER NOT NULL,
  peer_id NUMBER NOT NULL,
  course_id NUMBER NOT NULL,
  match_status VARCHAR2(16 CHAR) DEFAULT 'REQUESTED' NOT NULL,
  message VARCHAR2(500 CHAR),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT study_matches_pk PRIMARY KEY (study_match_id)
);

CREATE TABLE guidance_alerts (
  alert_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  student_id NUMBER NOT NULL,
  teacher_user_id NUMBER NOT NULL,
  course_id NUMBER,
  message VARCHAR2(500 CHAR) NOT NULL,
  alert_status VARCHAR2(16 CHAR) DEFAULT 'OPEN' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  sent_at TIMESTAMP,
  CONSTRAINT guidance_alerts_pk PRIMARY KEY (alert_id)
);

-- Purpose-built audit storage for the mark-update trigger.
CREATE TABLE mark_audit (
  audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  mark_id NUMBER NOT NULL,
  student_id NUMBER NOT NULL,
  assessment_id NUMBER NOT NULL,
  old_score NUMBER(7,2) NOT NULL,
  new_score NUMBER(7,2) NOT NULL,
  action_type VARCHAR2(12 CHAR) NOT NULL,
  changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  changed_by_user_id NUMBER,
  CONSTRAINT mark_audit_pk PRIMARY KEY (audit_id)
);
